    private void btnGenerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarActionPerformed
        // TODO add your handling code here:
        double suma=0;
        double promedio=0;
        for (int i = 0; i < kilometraje.length; i++) {
            suma+=kilometraje[i];
            promedio= suma/kilometraje.length;
        }
        String ubicacion="temp/";
        String nombre="victor_reporte_rutas";
        String ext=".txt";
        try (FileWriter fw= new FileWriter(ubicacion+nombre+ext)) {
           fw.append("Reporte Semanal de rutas"+"\n");
           fw.append("Total de kilometros: "+ suma+"\n");
           fw.append("Promedio diario: "+ promedio +"\n");
        } catch (IOException ex) {
            System.out.println("Error inesperado");
        }
    }//GEN-LAST:event_btnGenerarActionPerformed

