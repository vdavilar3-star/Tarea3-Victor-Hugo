    private void btnArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnArtistaActionPerformed
        // TODO add your handling code here:
        Artista a1= new Artista();
        a1.nombre=txtnombre.getText();
        a1.oyentes_mensuales= Integer.parseInt(txtoyentes.getText());
        a1.pais_origen= txtpais.getText();
        
        listaArtistas.add(a1);
        
        
    taContenido.append("Artista: " + a1.nombre + "  Oyentes: " + a1.oyentes_mensuales + " País: " + a1.pais_origen + "\n");
        
    txtnombre.setText("");
    txtoyentes.setText("");
    txtpais.setText("");
    }//GEN-LAST:event_btnArtistaActionPerformed

    private void btnCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancionActionPerformed
        // TODO add your handling code here:
        Cancion c1 = new Cancion();
            c1.titulo= txttitulo.getText();
            c1.nombre_artista= txtautor.getText();
            c1.duracion_segundos= Integer.parseInt(txtduracion.getText());
            c1.genero= txtgenero.getText();
            
            listaCanciones.add(c1);
    taContenido.append("Canción: " + c1.titulo + " Autor: " + c1.nombre_artista + " Duración: " + c1.duracion_segundos + " Género: " + c1.genero + "\n");
        txttitulo.setText("");
        txtautor.setText("");
        txtduracion.setText("");
        txtgenero.setText("");   
    }//GEN-LAST:event_btnCancionActionPerformed

