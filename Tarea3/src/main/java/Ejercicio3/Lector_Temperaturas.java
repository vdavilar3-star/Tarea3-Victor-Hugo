    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
        // TODO add your handling code here:
        File archivo= new File("temp/temperaturas.txt");
        try(Scanner sc= new Scanner(archivo)){
            while(sc.hasNextLine()){
             String linea= sc.nextLine();
             temperaturas[contador]= Double.parseDouble(linea);
             contador++;
            }
            JOptionPane.showMessageDialog(this, "Los datos fueron cargados en memoria");
        }catch(Exception e){
            System.out.println("Error inesperado :(");
        }
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
        double suma=0;
        double promedio=0;
        int diasC=0;
        int diasF=0;
        for (int i = 0; i < temperaturas.length; i++) {
            suma+=temperaturas[i];
        }
        promedio=suma/temperaturas.length;
        for (int i = 0; i < temperaturas.length; i++) {
            if (temperaturas[i]>=25.0) {
                diasC++;
                
            }else{
                diasF++;
            }
  
        }
        taContenido.append("Analisis Climatico "+"\n");
        taContenido.append("Promedio de temperaturas: "+ promedio+"\n");
        taContenido.append("Dias Calidos (>=25 grados) "+ diasC+"\n");
        taContenido.append("Dias Frescos (<=25 grados) "+ diasF+ "\n");
    }//GEN-LAST:event_btnCalcularActionPerformed

